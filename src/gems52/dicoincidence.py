def z_threshold(n_pairs: int, alpha: float = 0.05) -> float:
    """Two-sided normal threshold for ``alpha`` split over ``n_pairs`` -- a Bonferroni z, not a rune.

    The permutation test's own p-value cannot resolve below ``1/(n_perm+1)`` (0.0025 at 400 draws), so
    a Bonferroni p-gate over 100 pairs (0.0005) is *unreachable by construction* and would reject every
    pair for a reason that has nothing to do with the geology.  The z-score has no such floor, so it is
    the gate and the permutation p is reported next to it as a resolution-limited cross-check.
    """
    from math import sqrt
    from scipy.stats import norm
    if n_pairs <= 0:
        return float("inf")
    return float(norm.isf(alpha / (2.0 * n_pairs)))


def arm_scores(node: dict, pairs: list[dict], pct_by_pair: dict, z_gate: float | None = None,
               agree_deg: float = 22.5, tile_pct_gate: float = 0.90,
               surface_pct: float = 50.0) -> tuple[dict, dict]:
    """Per-node arm scores from **fabric-relative** coincidence evidence.

    The first version of this function gated on each pair's *global* z and on the local strike
    agreement, and it was useless: 37 of 100 pairs clear the global gate, so 93 % of candidate nodes
    counted as "corroborated" and 99.9 % as "A-corr".  The reason is geological, not statistical -- the
    whole province shares one N-S fabric, so two datasets agreeing in strike is the *default* here, not
    the exception.  The informative statement is therefore **relative to that pair's own behaviour**:
    a tile counts only when its agreement is unusual for *this pair* (``z_tile`` against the rolled
    null, which preserves the fabric), and a node counts only when its own tile is one of those.

    Definitions, all stated rather than tuned:

    * ``agree``    - the node's tile azimuths for two channels are within ``agree_deg`` (default 22.5,
      one eighth of the axial circle: the coarsest bin at which a 12-bin description is meaningful).
    * ``unusual``  - that tile sits in the top ``1 - tile_pct_gate`` (default top 10 %) of **this
      pair's own** tile-agreement distribution.  A per-tile *z-score* was tried first and is
      unreachable at this sample size: one tile contributes one scalar with a null s.d. of ~0.3, so
      |z| >= 3 would need cos2 >= 0.9 and fires on 0.0 % of tiles (measured), i.e. the gate would have
      been a silent no-op.  The percentile gate needs no variance estimate and its false-positive rate
      is the quantile itself, by construction.
    * ``B_corr``   - a surface channel (View B) with >= 1 field-family channel that is both ``agree``
      and ``unusual``.  "B confident, and independent physics corroborate *this place*."
    * ``A_corr``   - a node where >= 2 distinct **families** (magnetics/gravity/conductivity/
      radiometric/upward-continued-magnetics) are mutually ``agree`` and ``unusual`` *while the surface
      view is featureless here* (its own strength is below the ``surface_pct`` percentile of the node
      population, or its tile has no resolvable surface azimuth).  This is the brief's buried class.
    * ``B_only``   - a surface line with no corroboration at all: the suspect class (roads, levees,
      erosion), kept in the table so its measured value can be compared rather than asserted away.
    * ``union``    - every candidate, unweighted: the "no discovery logic" control on the same set.
    """
    keys = [k[len("theta_"):] for k in node if k.startswith("theta_")]
    surface = [k for k in keys if k in SURFACE_KEYS]
    field = [k for k in keys if k not in SURFACE_KEYS]
    fam_of: dict[str, str] = {}
    for k in keys:
        if k in surface:
            fam_of[k] = "surface"
    for p in pairs:
        fam_of[p["a"]] = p["family_a"]
        fam_of[p["b"]] = p["family_b"]
    cos_crit = float(np.cos(2.0 * np.deg2rad(agree_deg)))
    n = node["row"].size
    theta = {k: node[f"theta_{k}"] for k in keys}
    strength = {k: np.nan_to_num(node[f"strength_{k}"], nan=0.0) for k in keys}

    def pairwise_flag(k: str, r: str) -> np.ndarray:
        """Boolean per node: channels k and r agree *and* the agreement is unusual for this pair."""
        pmap = pct_by_pair.get((k, r))
        if pmap is None:
            pmap = pct_by_pair.get((r, k))
        if pmap is None:
            return np.zeros(n, dtype=bool)
        ta, tb = theta[k], theta[r]
        ok = np.isfinite(ta) & np.isfinite(tb)
        pct = pmap[node["tile"]]
        flag = np.zeros(n, dtype=bool)
        flag[ok] = np.cos(2.0 * A.axial_difference(ta[ok], tb[ok])) >= cos_crit
        return flag & np.isfinite(pct) & (pct >= tile_pct_gate)

    # per-channel corroboration counts (over channels of *different* families)
    corr_cnt = {}
    for k in keys:
        cnt = np.zeros(n, dtype=np.int32)
        for r in keys:
            if r == k or fam_of.get(r) == fam_of.get(k):
                continue
            cnt += pairwise_flag(k, r).astype(np.int32)
        corr_cnt[k] = cnt
    surf_strength = (np.maximum.reduce([strength[k] for k in surface]) if surface
                     else np.zeros(n))
    b_corr_cnt = (np.maximum.reduce([corr_cnt[k] for k in surface]) if surface
                  else np.zeros(n, dtype=np.int32))

    # families mutually agreeing, for the A-corr (buried) class
    fam_agree = {}
    for k in field:
        cnt = np.zeros(n, dtype=np.int32)
        for r in field:
            if r == k or fam_of.get(r) == fam_of.get(k):
                continue
            cnt += pairwise_flag(k, r).astype(np.int32)
        fam_agree[k] = cnt
    a_support = np.maximum.reduce(list(fam_agree.values())) if fam_agree else np.zeros(n, dtype=np.int32)
    a_families = np.zeros(n, dtype=np.int32)
    for k in field:
        a_families += (fam_agree[k] > 0).astype(np.int32)

    surf_thr = float(np.percentile(surf_strength, surface_pct))
    surface_featureless = (surf_strength <= surf_thr)
    for k in surface:
        surface_featureless |= ~np.isfinite(theta[k])
    cover = np.nan_to_num(node["cover_rank"], nan=0.0)
    arms = {
        "B_corr": np.where(b_corr_cnt > 0, surf_strength * (1.0 + b_corr_cnt), 0.0),
        "A_corr": np.where((a_families >= 2) & surface_featureless,
                           1.0 + np.minimum(a_support, 5) + cover, 0.0),
        "A_corr_deep": np.where((a_families >= 2) & surface_featureless & (cover >= 0.6),
                                2.0 + np.minimum(a_support, 5), 0.0),
        "B_only": np.where(b_corr_cnt == 0, surf_strength, 0.0),
        "union": np.maximum(surf_strength,
                            (np.maximum.reduce([strength[k] for k in field]) if field
                             else surf_strength)),
        "field_only": (np.maximum.reduce([strength[k] for k in field]) if field
                       else np.zeros(n)),
    }
    meta = {"n_surface_channels": len(surface), "n_field_channels": len(field),
            "n_pairs": len(pairs), "tile_pct_gate": tile_pct_gate, "agree_deg": agree_deg,
            "surface_strength_threshold": surf_thr,
            "z_gate_global_for_reference": z_gate,
            "share_b_corr": float((b_corr_cnt > 0).mean()),
            "share_a_corr": float(((a_families >= 2) & surface_featureless).mean()),
            "share_a_corr_deep": float(((a_families >= 2) & surface_featureless & (cover >= 0.6)).mean()),
            "share_featureless": float(surface_featureless.mean()),
            "b_corr_counts": {int(k): float((b_corr_cnt >= k).mean()) for k in (1, 2, 3)},
            "a_family_counts": {int(k): float((a_families >= k).mean()) for k in (1, 2, 3, 4)}}
    return arms, meta

