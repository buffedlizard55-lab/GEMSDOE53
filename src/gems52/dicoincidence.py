"""H53-1 · Cross-dataset **orientation coincidence** with a randomization null.

The hypothesis this implements
------------------------------
A fault trace is a *line* in several physically independent datasets at once.  The catalogue that the
competition scores against was built by manual interpretation (USGS Quaternary fault maps + the
INGENIOUS compilation), and every published note in this family agrees on the failure mode of
automatic mappers in this province: they fire on roads, canals, levees, canyon rims and stream banks
because those are linear in **one** dataset (topography) and nothing else (Hermant, Kiersnowski &
Bellanger 2025, 50th Stanford Geothermal Workshop, https://pangea.stanford.edu/ERE/db/GeoConf/papers/SGW/2025/Hermant.pdf ,
listed by the organisers on the competition's own About page as recommended reading).

So the discriminating question is not "is there a line here" -- a single view answers that, and the
0.2778 baseline file answers it 37,654 times -- but **"do independent physics agree that it is a
line, at this place, with this strike?"**  This module answers exactly that question and calibrates
"agree" against a randomization null instead of a hand-picked threshold.

What is measured, and what it is not
------------------------------------
Per dataset ``c`` the structure tensor (``gems52.structure``) gives an azimuth field.  At 1.6 km tiles
that field is reduced to a weighted axial mean azimuth with a concentration ``R``, and for a pair of
datasets ``(c, d)`` the coincidence statistic is

    obs(c,d) = mean over tiles of cos( 2 * (theta_c - theta_d) )        (null 0, see gems52.azimuth)

with the null distribution generated by **rolling one azimuth field across the tile grid** -- a
circular shift that preserves each field's own spatial structure and destroys only the pointwise
pairing.  That is the correct null for "these two fields agree at the same place": a null built from
shuffling individual tiles would inflate significance by breaking the autocorrelation that makes
neighbouring tiles identical.  ``p`` is the standard ``(1 + #{null >= obs}) / (1 + n_perm)``.

Two things this module deliberately does **not** do:

* It does not use any truth label.  The permutation test is unsupervised; nothing here is fitted to
  the catalogue, so a candidate it produces is not a copy of the catalogue by construction.
* It does not claim the datasets are independent in the statistical sense.  Magnetic and gravity
  grids share a processing heritage, and the "families" below (magnetics / gravity / radar /
  radiometric / topographic) are the *physics* level at which a coincidence is meaningful.  The
  requirement that agreement come from **different families** is what stops "two magnetic bands agree"
  from being counted twice; the number of families, not the number of files, is the sample size.

Data sources (all already in this repository, hash-pinned; see registry/data_manifest.json):
  * official competition cube ``data/training_features.tif``, 19 float32 bands, EPSG:32611 @ 100 m;
  * ``data/external/geodawn_rad_u8.tif``  -- GeoDAWN airborne gamma-ray spectrometry K, Th, U, TC
    (USGS GeoDAWN release; the competition's own About page points at GeoDAWN:
    https://www.sciencebase.gov/catalog/item/657e1d85d34e23d3533209f7 );
  * ``data/external/geodawn_extensions_u8.tif`` -- derived ternary ratios and an upward-continued TMI
    (``TMI_up150``), i.e. a depth-filtered magnetic grid that suppresses shallow sources.
"""

