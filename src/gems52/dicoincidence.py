def tile_index(shape: tuple[int, int], tile: int = TILE_PX) -> tuple[np.ndarray, np.ndarray, tuple[int, int]]:
    """Flat tile id per pixel, the row-of-tiles index, and the (n_rows, n_cols) tile grid shape."""
    h, w = shape
    tr = np.arange(h) // tile
    tc = np.arange(w) // tile
    n_cols = (w + tile - 1) // tile
    n_rows = (h + tile - 1) // tile
    return tr[:, None] * n_cols + tc[None, :], tr, (n_rows, n_cols)


def tile_azimuth(az: np.ndarray, weight: np.ndarray, tid: np.ndarray, n_tiles: int,
                 min_weight: float = 8.0) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Weighted axial mean azimuth per tile, its concentration R, and the weight mass.

    Returns ``(theta[tile] or NaN, R[tile], mass[tile])``.  A tile whose total weight is below
    ``min_weight`` has no azimuth: a 1.6 km tile with 8 coherent pixels is not evidence of anything,
    and leaving it NaN is what keeps the permutation test honest about the number of usable tiles.
    """
    z2 = 2.0 * az
    ok = np.isfinite(z2) & np.isfinite(weight) & (weight > 0)
    c = np.where(ok, weight * np.cos(z2), 0.0)
    s = np.where(ok, weight * np.sin(z2), 0.0)
    wsum = np.where(ok, weight, 0.0)
    flat = tid.ravel()
    nc = np.bincount(flat[ok.ravel()], weights=c.ravel()[ok.ravel()], minlength=n_tiles)
    ns = np.bincount(flat[ok.ravel()], weights=s.ravel()[ok.ravel()], minlength=n_tiles)
    nm = np.bincount(flat[ok.ravel()], weights=wsum.ravel()[ok.ravel()], minlength=n_tiles)
    theta = np.full(n_tiles, np.nan)
    r = np.zeros(n_tiles)
    good = nm >= min_weight
    theta[good] = np.mod(0.5 * np.arctan2(ns[good], nc[good]), np.pi)
    r[good] = np.hypot(nc[good], ns[good]) / np.maximum(nm[good], 1e-12)
    return theta, r, nm


def coincidence_test(theta_a: np.ndarray, theta_b: np.ndarray, tile_shape: tuple[int, int],
                     n_perm: int = 400, seed: int = 0) -> tuple[dict, np.ndarray]:
    """Permutation test for "do these two azimuth fields agree at the same place?".

    The null rolls field ``b`` across the **tile grid** by a random offset: each field keeps its own
    spatial structure (autocorrelation, patchiness, gaps) and only the pointwise pairing is destroyed.
    That is the correct null for a same-place question; shuffling tiles individually would instead
    break the autocorrelation that makes neighbouring tiles near-identical, and would manufacture
    significance out of nothing.

    Two implementation facts that were bugs first and are now contract:

    * **The usable set is recomputed for every draw.**  Rolling ``b`` moves its NaN tiles around, so a
      draw's statistic must be taken over the tiles where *that draw's* rotated field is finite.  Using
      the observed trial's mask instead leaves NaN in the null and produced ``null_mean = nan`` -- and
      a z-score of NaN would have silently disabled every significance gate downstream.
    * **``null_mean``/``null_sd`` are computed over the finite draws only**, and the number of dropped
      draws is reported rather than hidden.

    Returns ``(summary, z_tile)`` where ``z_tile`` is a per-tile z-score of the observed agreement
    against the pooled per-tile null distribution (NaN where either field has no azimuth).  ``z_tile``
    is what makes the test usable *locally* -- a global p-value says "these two grids are related",
    while the local decision ("is the agreement at this tile unusual") needs the per-tile null.
    """
    if theta_a.shape != theta_b.shape:
        raise ValueError("tile grids must have the same shape")
    a = np.asarray(theta_a, dtype=np.float64).reshape(tile_shape)
    b = np.asarray(theta_b, dtype=np.float64).reshape(tile_shape)
    fin_a = np.isfinite(a)
    fin_b = np.isfinite(b)
    ok0 = fin_a & fin_b
    n_use = int(ok0.sum())
    if n_use < 12:
        return ({"obs": float("nan"), "p": float("nan"), "z": float("nan"), "n_tiles": n_use,
                 "n_perm": n_perm, "usable": False}, np.full(tile_shape, np.nan),
                np.full(tile_shape, np.nan))
    obs = float(np.mean(np.cos(2.0 * A.axial_difference(a[ok0], b[ok0]))))
    rng = np.random.default_rng(seed)
    h, w = tile_shape
    null = np.full(n_perm, np.nan)
    pooled_sum = np.zeros(tile_shape)
    pooled_sq = np.zeros(tile_shape)
    pooled_cnt = np.zeros(tile_shape)
    ns = []
    for i in range(n_perm):
        dy, dx = int(rng.integers(h)), int(rng.integers(w))
        br = np.roll(np.roll(b, dy, axis=0), dx, axis=1)
        okp = fin_a & np.isfinite(br)
        n = int(okp.sum())
        if n < 12:
            continue
        c2 = np.cos(2.0 * A.axial_difference(a[okp], br[okp]))
        null[i] = float(np.mean(c2))
        pooled_sum[okp] += c2
        pooled_sq[okp] += c2 * c2
        pooled_cnt[okp] += 1.0
        ns.append(n)
    good = np.isfinite(null)
    if good.sum() < 20:
        return ({"obs": obs, "p": float("nan"), "z": float("nan"), "n_tiles": n_use,
                 "n_perm": int(good.sum()), "usable": False}, np.full(tile_shape, np.nan),
                np.full(tile_shape, np.nan))
    nm = float(np.mean(null[good]))
    nsd = float(np.std(null[good]))
    ge = int((null[good] >= obs).sum())
    cnt = np.maximum(pooled_cnt, 1.0)
    tile_null_mean = np.where(pooled_cnt > 0, pooled_sum / cnt, np.nan)
    tile_null_var = np.where(pooled_cnt > 1, np.maximum(pooled_sq / cnt - tile_null_mean ** 2, 0.0),
                             np.nan)
    tile_sd = np.sqrt(tile_null_var)
    sel = pooled_cnt >= 30                     # a tile needs enough draws for a stable sd
    cos2_tile = np.where(ok0, np.cos(2.0 * A.axial_difference(a, b)), np.nan)
    with np.errstate(invalid="ignore", divide="ignore"):
        z_tile = np.where(ok0 & sel & (tile_sd > 1e-9),
                          (cos2_tile - tile_null_mean) / np.maximum(tile_sd, 1e-12), np.nan)
    summary = {"obs": obs, "p": (1.0 + ge) / (1.0 + int(good.sum())), "n_tiles": n_use,
               "n_perm": int(good.sum()), "null_mean": nm, "null_sd": nsd,
               "null_p95": float(np.percentile(null[good], 95)),
               "z": float((obs - nm) / max(nsd, 1e-12)) if nsd > 0 else float("nan"),
               "mean_tiles_per_draw": float(np.mean(ns)) if ns else float("nan"),
               "tiles_with_stable_tile_z": int((sel & ok0).sum()),
               "usable": True}
    # `cos2_tile` is returned alongside the z-map because a *distribution-free* gate is what the data
    # can actually support: a tile contributes one scalar, whose null s.d. is ~0.3, so |z| >= 3 would
    # require cos2 >= 0.9 and fires on 0.0 % of tiles -- a silently disabled gate.  The rank of a
    # tile's cos2 within its own pair's tile population needs no s.d. at all.
    return summary, z_tile, cos2_tile


