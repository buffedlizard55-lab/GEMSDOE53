def footprint() -> np.ndarray:
    """The competition footprint, measured from the sample submission (finite = inside)."""
    with rasterio.open("data/sample_submission.tif") as ds:
        return np.isfinite(ds.read(1))


def catalogue() -> np.ndarray:
    with rasterio.open("data/labels.tif") as ds:
        return ds.read(1) == 1


def read_channel(spec: ChannelSpec, valid: np.ndarray) -> np.ndarray:
    with rasterio.open(spec.path) as ds:
        a = ds.read(spec.band).astype(np.float32)
    a[~np.isfinite(a)] = np.nan
    a[a < -1e38] = np.nan
    return np.where(valid, a, np.nan)


