def _channel_lines(spec: ChannelSpec, valid: np.ndarray, sigma_tensor_m: float,
                   coh_gate: float, persist_gate: float, allowed: np.ndarray,
                   topk: int) -> dict:
    """One channel -> candidates, per-pixel line strength, and tile azimuths (pass 1 + pass 2).

    Returned arrays are either full-grid (``strength``, used once and dropped) or per-tile; the
    per-node extraction happens in :func:`build`, after the candidate union is known, so no per-channel
    full-grid arrays are ever held for more than one channel at a time.
    """
    a = read_channel(spec, valid)
    st = S.structure_tensor(a, valid, sigma_tensor_m=sigma_tensor_m)
    del a
    persist = S.oriented_line_energy(st["azimuth"], valid, sigma_m=sigma_tensor_m)
    coh = np.nan_to_num(st["coherence"], nan=0.0)
    per = np.nan_to_num(persist, nan=0.0)
    e_rank = np.nan_to_num(T_rank01(st["energy"], valid), nan=0.0).astype(np.float32)
    strength = (coh * per * e_rank).astype(np.float32)
    gate = allowed & (st["coherence"] > coh_gate) & (persist > persist_gate)
    cand = ND.local_maxima(np.where(gate, strength, 0.0), gate, radius_px=1)
    if int(cand.sum()) > topk:
        cand = ND.top_k_mask(strength, cand, topk)
    return {"cand": cand, "strength": strength, "coh": coh, "persist": per,
            "azimuth": st["azimuth"], "energy": st["energy"]}


def build_tiles(work_dir: str = "work/dicoincidence", sigma_tensor_m: float = 300.0,
                tile_px: int = TILE_PX, topk_per_channel: int = 60_000, coh_gate: float = 0.30,
                persist_gate: float = 0.35, log=print) -> dict:
    """Pass 1: candidates per channel + tile azimuths.  ~2 minutes, ~350 MB, writes tiles.npz.

    Staged on purpose: the permutation test and the arm rules are where the *thinking* changes and the
    tensors are where the *time* goes, so the expensive half is cached and only the cheap half re-runs
    when a statistic is corrected.  A single end-to-end function was rewritten five times in one
    session otherwise.
    """
    out = Path(work_dir)
    out.mkdir(parents=True, exist_ok=True)
    valid = footprint()
    cat = catalogue()
    allowed = valid & ~cat
    tid, _, tile_shape = tile_index(valid.shape, tile_px)
    n_tiles = int(tile_shape[0] * tile_shape[1])
    log(f"footprint {int(valid.sum())} px, catalogue {int(cat.sum())} px, "
        f"tiles {tile_shape[0]}x{tile_shape[1]} ({tile_px} px = {tile_px * PIXEL_M / 1000:.1f} km)")

    per_channel: dict[str, dict] = {}
    cand_union = np.zeros(valid.shape, dtype=bool)
    for spec in CHANNELS:
        d = _channel_lines(spec, valid, sigma_tensor_m, coh_gate, persist_gate, allowed,
                           topk_per_channel)
        n_cand = int(d["cand"].sum())
        cand_union |= d["cand"]
        theta_t, r_t, mass_t = tile_azimuth(d["azimuth"], d["coh"] * d["persist"], tid, n_tiles)
        per_channel[spec.key] = {"spec": spec, "theta": theta_t, "R": r_t, "mass": mass_t,
                                 "n_candidates": n_cand}
        log(f"  [pass 1] {spec.key:14s} family={spec.family:12s} candidates {n_cand:>7d}, "
            f"tiles with a resolvable azimuth {int(np.isfinite(theta_t).sum()):>6d}/{n_tiles}")
        del d
    log(f"candidate union: {int(cand_union.sum())} px")
    if not cand_union.any():
        raise RuntimeError("no candidates: thresholds are impossible on this data")
    np.savez_compressed(out / "tiles.npz",
                        tile_shape=np.array(tile_shape, dtype=np.int64),
                        candidate_px=np.array(cand_union.sum(), dtype=np.int64),
                        **{f"{k}__{f}": v for k, d in per_channel.items()
                           for f, v in (("theta", d["theta"]), ("R", d["R"]), ("mass", d["mass"]))},
                        **{f"ncand__{k}": np.array(d["n_candidates"], dtype=np.int64)
                           for k, d in per_channel.items()})
    return {"per_channel": per_channel, "tile_shape": tile_shape, "n_tiles": n_tiles,
            "cand_union": cand_union, "tile_px": tile_px, "sigma_tensor_m": sigma_tensor_m,
            "coh_gate": coh_gate, "persist_gate": persist_gate,
            "topk_per_channel": topk_per_channel}


def load_tiles(work_dir: str = "work/dicoincidence") -> dict:
    """Rebuild the pass-1 dict from ``tiles.npz`` without touching a raster."""
    z = np.load(Path(work_dir) / "tiles.npz")
    tile_shape = tuple(int(v) for v in z["tile_shape"])
    per_channel = {}
    for spec in CHANNELS:
        per_channel[spec.key] = {
            "spec": spec, "theta": z[f"{spec.key}__theta"], "R": z[f"{spec.key}__R"],
            "mass": z[f"{spec.key}__mass"], "n_candidates": int(z[f"ncand__{spec.key}"]),
        }
    return {"per_channel": per_channel, "tile_shape": tile_shape,
            "n_tiles": int(tile_shape[0] * tile_shape[1]),
            "candidate_px": int(z["candidate_px"]),
            "cand_union": None}


def agreement_percentile(cos2_tile: np.ndarray) -> np.ndarray:
    """Rank each tile's observed agreement within its own pair's tile population, in [0, 1].

    Distribution-free on purpose: it says "this tile agrees better than 90 % of the tiles this pair can
    be measured on", which needs no variance estimate and is therefore robust to the strong spatial
    autocorrelation that makes a per-tile z-score meaningless (neighbouring tiles are not independent
    samples of the same pair).
    """
    c = np.asarray(cos2_tile, dtype=np.float64)
    out = np.full(c.shape, np.nan)
    fin = np.isfinite(c)
    n = int(fin.sum())
    if n == 0:
        return out
    from scipy.stats import rankdata
    out[fin] = rankdata(c[fin], method="average") / n
    return out


def coincidence_table(tiles: dict, n_perm: int = 400, seed: int = 0, log=print) -> tuple[list, dict]:
    """Pass 2a: the family-disjoint permutation tests.  Cheap; re-run whenever a statistic changes."""
    per_channel = tiles["per_channel"]
    tile_shape = tiles["tile_shape"]
    keys = [c.key for c in CHANNELS]
    pairs, z_by_pair, pct_by_pair = [], {}, {}
    for i, ki in enumerate(keys):
        for kj in keys[i + 1:]:
            fi, fj = per_channel[ki]["spec"].family, per_channel[kj]["spec"].family
            if fi == fj:
                continue
            res, z_tile, cos2_tile = coincidence_test(per_channel[ki]["theta"],
                                                      per_channel[kj]["theta"],
                                                      tile_shape, n_perm=n_perm, seed=seed)
            if not res["usable"]:
                continue
            fin = np.isfinite(z_tile)
            res.update({"a": ki, "b": kj, "family_a": fi, "family_b": fj,
                        "tile_z_share_ge3": float((z_tile[fin] >= 3.0).mean()) if fin.any() else None,
                        "tile_z_share_le_m3": float((z_tile[fin] <= -3.0).mean()) if fin.any() else None})
            # flattened to the same row-major tile order tile_index() hands to the nodes; a 2-D map
            # indexed by a flat tile id silently reads the wrong tile (or raises) -- it raised.
            z_by_pair[(ki, kj)] = np.asarray(z_tile).reshape(-1)
            pct_by_pair[(ki, kj)] = agreement_percentile(cos2_tile).reshape(-1)
            pairs.append(res)
    pairs.sort(key=lambda r: r["p"])
    zt = z_threshold(len(pairs))
    if pairs:
        log(f"coincidence pairs tested: {len(pairs)} (family-disjoint); best: {pairs[0]['a']} vs "
            f"{pairs[0]['b']} obs {pairs[0]['obs']:+.3f}, null {pairs[0]['null_mean']:+.4f} "
            f"+- {pairs[0]['null_sd']:.4f}, z {pairs[0]['z']:+.1f}, p {pairs[0]['p']:.4f}")
    log(f"pairs clearing the Bonferroni z gate (|z| >= {zt:.2f}): "
        f"{sum(1 for p in pairs if p['z'] >= zt)} of {len(pairs)}")
    return pairs, {"z_gate": zt, "z_by_pair": z_by_pair, "pct_by_pair": pct_by_pair}


def build_nodes(tiles: dict, pairs: list, work_dir: str = "work/dicoincidence",
                n_perm: int = 400, seed: int = 0, log=print) -> dict:
    """Pass 2b: per-node evidence for every channel, written to nodes.npz."""
    out = Path(work_dir)
    valid = footprint()
    allowed = valid & ~catalogue()
    sigma_tensor_m = tiles.get("sigma_tensor_m", 300.0)
    coh_gate, persist_gate = tiles.get("coh_gate", 0.30), tiles.get("persist_gate", 0.35)
    topk = tiles.get("topk_per_channel", 60_000)
    cand_union = tiles["cand_union"]
    if cand_union is None:
        raise RuntimeError("build_nodes needs the in-memory candidate union from build_tiles")
    ys_all, xs_all = np.nonzero(cand_union)
    tid, _, _ = tile_index(valid.shape, tiles["tile_px"])
    t_at_node = tid[ys_all, xs_all]
    node = {"row": ys_all.astype(np.int32), "col": xs_all.astype(np.int32),
            "tile": t_at_node.astype(np.int32)}
    for spec in CHANNELS:
        d = _channel_lines(spec, valid, sigma_tensor_m, coh_gate, persist_gate, allowed, topk)
        node[f"coh_{spec.key}"] = d["coh"][ys_all, xs_all].astype(np.float32)
        node[f"persist_{spec.key}"] = d["persist"][ys_all, xs_all].astype(np.float32)
        node[f"strength_{spec.key}"] = d["strength"][ys_all, xs_all].astype(np.float32)
        node[f"theta_{spec.key}"] = tiles["per_channel"][spec.key]["theta"][t_at_node].astype(np.float32)
        node[f"tileR_{spec.key}"] = tiles["per_channel"][spec.key]["R"][t_at_node].astype(np.float32)
        del d
        log(f"  [pass 2] {spec.key:14s} node evidence extracted")
    cover = read_channel(ChannelSpec("depth_to_base", OFFICIAL, 15, "subsurface",
                                     "thickness of sedimentary cover"), valid)
    cover_rank = np.nan_to_num(T_rank01(cover, valid), nan=0.5)
    node["cover_rank"] = cover_rank[ys_all, xs_all].astype(np.float32)
    del cover, cover_rank
    np.savez_compressed(out / "nodes.npz", **node)
    log(f"wrote {out / 'nodes.npz'} ({ys_all.size} candidates)")
    return node


def build(work_dir: str = "work/dicoincidence", sigma_tensor_m: float = 300.0,
          tile_px: int = TILE_PX, n_perm: int = 400, topk_per_channel: int = 60_000,
          coh_gate: float = 0.30, persist_gate: float = 0.35, seed: int = 0,
          log=print) -> dict:
    """Run the whole detector and persist node features + the coincidence evidence.

    Memory strategy, stated because the first version of this function died here: the competition
    grid is 12.3 Mpix, so *one* full-grid float32 array is 49 MB and a channel needs about eight of
    them.  Pass 1 therefore keeps only candidates and per-tile azimuths, and pass 2 re-reads each
    channel to extract its values **at the node coordinates only**.  Recomputing the tensor costs
    ~4 minutes and saves ~2.3 GB, which on this box is the difference between a table and an
    out-of-memory kill.

    Steps, in order, with the reason each one is where it is:

    1. **Candidates (pass 1).** Every channel's structure tensor is reduced to ``line_strength``
       (coherence x along-strike persistence x energy rank) and its local maxima are candidates.  The
       candidate set is deliberately *blind*: top ``topk_per_channel`` per channel, no truth involved.
    2. **Tile azimuths.** Each channel's azimuth field becomes one azimuth per 1.6 km tile.
    3. **Coincidence.** Every family-disjoint channel pair gets a permutation test.
    4. **Node evidence (pass 2).** Each candidate reads off, per channel, its own coherence /
       persistence / strength and the azimuth of its tile; :func:`arm_scores` combines that evidence.
    5. Persist ``nodes.npz`` and ``evidence/dicoincidence.json``.
    """
    tiles = build_tiles(work_dir=work_dir, sigma_tensor_m=sigma_tensor_m, tile_px=tile_px,
                        topk_per_channel=topk_per_channel, coh_gate=coh_gate,
                        persist_gate=persist_gate, log=log)
    pairs, pm = coincidence_table(tiles, n_perm=n_perm, seed=seed, log=log)
    node = build_nodes(tiles, pairs, work_dir=work_dir, n_perm=n_perm, seed=seed, log=log)
    arms, meta = arm_scores(node, pairs, p_crit=0.05 / max(len(pairs), 1), z_gate=pm["z_gate"])
    node_scores = {k: v for k, v in arms.items()}
    np.savez_compressed(Path(work_dir) / "arms.npz",
                        **{k: v.astype(np.float32) for k, v in node_scores.items()})
    ev = {
        "what": "H53-1 cross-dataset orientation coincidence, permutation-calibrated",
        "tile_px": tile_px, "tile_km": tile_px * PIXEL_M / 1000.0,
        "sigma_tensor_m": sigma_tensor_m, "n_perm": n_perm, "seed": seed,
        "coh_gate": coh_gate, "persist_gate": persist_gate, "topk_per_channel": topk_per_channel,
        "candidate_union_px": int(tiles["cand_union"].sum()),
        "channels": [{"key": c.key, "path": c.path, "band": c.band, "family": c.family,
                      "physical": c.physical,
                      "n_candidates": tiles["per_channel"][c.key]["n_candidates"],
                      "tiles_with_azimuth": int(np.isfinite(
                          tiles["per_channel"][c.key]["theta"]).sum())}
                     for c in CHANNELS],
        "coincidence_pairs": pairs, "p_bonferroni": 0.05 / max(len(pairs), 1),
        "z_gate": pm["z_gate"], "arm_meta": meta,
    }
    (Path("evidence") / "dicoincidence.json").write_text(json.dumps(ev, indent=1, default=str))
    log(f"wrote {Path(work_dir) / 'arms.npz'} and evidence/dicoincidence.json")
    return ev


