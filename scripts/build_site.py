def esc(x):
    return html.escape(str(x))


def f4(x):
    try:
        return f"{float(x):.4f}"
    except (TypeError, ValueError):
        return "n/a"


def sha(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for c in iter(lambda: 1 << 20, b""):
            h.update(c)
    return h.hexdigest()


